const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const code = fs.readFileSync(path.join(__dirname, 'monitor/monitor.js'), 'utf8');
const helpers = code.slice(code.indexOf('  function parseNinferThroughput'), code.indexOf('  let throughputLog'));
const {parseNinferThroughput: parse, ninferLiveSpeed: speed} = vm.runInNewContext(helpers + ';({parseNinferThroughput,ninferLiveSpeed})');
const at = new Date('2026-10-25T15:00:00.000').getTime();
const line = (body, interval='5.0s') => `2026-10-25 15:00:00.000  INFO  throughput | ${interval} | ${body} | running 1 (decode-ready 1) | batch 1.00\n`;
const log = text => ({running:true,backend:'ninfer',started_at:at-60000,text});
const native = line('decode 58.4 tok/s (292 tok)');
const sample = parse(log(native)), snapshot = {sampled_at_ms:at+500}, row = {status:'generating',started_at_ms:at-10000,decode_tps:41.5};
assert.equal(sample.rate,58.4);
assert.equal(sample.seconds,5);
assert.equal(speed(snapshot,row,true,sample),58.4,'native interval rate differs from request mean');
assert.equal(row.decode_tps,41.5,'request mean is untouched');
assert.equal(speed({sampled_at_ms:at+13000},row,true,sample),null,'stale logs expire');
assert.equal(speed(snapshot,{...row,started_at_ms:at+1},true,sample),null,'previous request cannot leak');
assert.equal(speed(snapshot,row,false,sample),null,'history has no realtime speed');
assert.equal(speed(snapshot,{...row,status:'reading'},true,sample),null,'prefill is not live decoding');
assert.equal(speed(snapshot,row,true,null),null,'unavailable logs do not substitute mean');
assert.equal(parse({...log(native),running:false}),null);
assert.equal(parse({...log(native),backend:'polystrata'}),null);
assert.equal(parse({...log(native),started_at:at+1}),null,'old session is rejected');
assert.equal(parse(log('user text: '+native)),null,'only anchored operational records count');
assert.equal(parse(log('\x1b[32m'+native+'\x1b[0m')).rate,58.4);
assert.equal(parse(log(line('prefill 1.20k tok/s (6,000 tok)'))).rate,0,'no decode in interval is zero');
assert.equal(parse(log(line('decode 1.20k tok/s (6,000 tok)'))).rate,1200);
assert.equal(parse(log(line('decode 40.0 tok/s (20 tok)','500 ms'))).seconds,0.5);
assert.equal(parse(log(native+line('decode n/a tok/s (292 tok)'))),null,'malformed latest rate does not keep an old rate');
console.log('PASS: native interval rate, cumulative mean separation, stale/request/session boundaries, log formats.');
